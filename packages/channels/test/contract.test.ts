import { randomUUID } from 'node:crypto';
import { describe, expect, it } from 'vitest';
import {
  FixtureEmailAdapter,
  MemoryEvidenceStore,
  MemorySink,
  parseEmail,
  senderAuthentication,
  signSyntheticRequest,
  SIGNATURE_HEADER,
  stripQuotedReply,
  isAutoGenerated,
  SyntheticChatAdapter,
  InboundRejectedError,
  type ConnectionContext,
} from '@swipeback/channels';
import { buildEml, channelContractSuite } from '@swipeback/channels/testing';

const tenantId = randomUUID();
const SECRET = 'test-signing-secret-0123456789';

channelContractSuite('email (fixture transport)', async () => {
  const evidence = new MemoryEvidenceStore();
  const sink = new MemorySink();
  const connection: ConnectionContext = { tenantId, connectionId: randomUUID(), channel: 'email', provider: 'fixture', address: 'finance@northwind.example' };
  return {
    adapter: new FixtureEmailAdapter(evidence, sink),
    connection,
    evidence,
    sink,
    senderAddress: 'Sam.Taylor@northwind.example',
    expectedAuthentication: 'dkim_aligned',
    tamperOutcome: 'unauthenticated',
    validInbound: ({ senderAddress, senderDisplayName, attachment, text }) => ({
      body: buildEml({ from: senderAddress, fromName: senderDisplayName, to: connection.address, text, attachments: [{ filename: 'r.png', mime: 'image/png', content: attachment }] }),
      headers: {},
    }),
    // Forged auth stamp from a server we do not trust.
    tamper: (raw) => ({ ...raw, body: Buffer.from(raw.body.toString('utf8').replace('Authentication-Results: fixture.swipeback.test', 'Authentication-Results: evil.example')) }),
  };
});

channelContractSuite('synthetic chat (signed webhook)', async () => {
  const evidence = new MemoryEvidenceStore();
  const sink = new MemorySink();
  const connection: ConnectionContext = { tenantId, connectionId: randomUUID(), channel: 'synthetic', provider: 'synthetic-chat', address: 'swipeback-bot' };
  return {
    adapter: new SyntheticChatAdapter(evidence, sink, SECRET),
    connection,
    evidence,
    sink,
    senderAddress: 'chat:sam.taylor',
    expectedAuthentication: 'platform_signed',
    tamperOutcome: 'reject',
    validInbound: ({ senderAddress, senderDisplayName, attachment, text }) => {
      const body = JSON.stringify({
        eventId: randomUUID(),
        from: senderAddress,
        displayName: senderDisplayName,
        text,
        sentAt: new Date().toISOString(),
        attachments: [{ filename: 'r.png', mime: 'image/png', dataBase64: attachment.toString('base64') }],
      });
      return { body: Buffer.from(body), headers: { [SIGNATURE_HEADER]: signSyntheticRequest(SECRET, body, Math.floor(Date.now() / 1000)) } };
    },
    tamper: (raw) => ({ ...raw, body: Buffer.from(raw.body.toString('utf8').replace('"text":"', '"text":"tampered ')) }),
  };
});

describe('email specifics', () => {
  const conn: ConnectionContext = { tenantId, connectionId: randomUUID(), channel: 'email', provider: 'fixture', address: 'finance@northwind.example' };
  const adapter = new FixtureEmailAdapter(new MemoryEvidenceStore(), new MemorySink());

  it('only processes mail addressed to the designated address (or its plus-aliases)', async () => {
    const other = buildEml({ from: 'sam.taylor@northwind.example', to: 'someone.else@northwind.example', text: 'hi' });
    await expect(adapter.verifyInbound(conn, { body: other, headers: {} })).rejects.toMatchObject({ reason: 'NOT_ADDRESSED_TO_CONNECTION' });
    const plus = buildEml({ from: 'sam.taylor@northwind.example', to: 'finance+q-abc12345@northwind.example', text: 'Company card' });
    const event = await adapter.normaliseInbound(await adapter.verifyInbound(conn, { body: plus, headers: {} }));
    expect(event.conversation.correlationToken).toBe('abc12345');
  });

  it('trusts only the topmost Authentication-Results from our receiving server, and requires alignment', async () => {
    const forgedBelow = buildEml({ from: 'ceo@northwind.example', to: conn.address, auth: { authservId: 'mx.attacker.example', result: 'pass' }, extraHeaders: {} });
    expect(senderAuthentication(await parseEmail(forgedBelow), ['fixture.swipeback.test'])).toBe('none');
    const failed = buildEml({ from: 'sam.taylor@northwind.example', to: conn.address, auth: 'fail' });
    expect(senderAuthentication(await parseEmail(failed), ['fixture.swipeback.test'])).toBe('none');
    const none = buildEml({ from: 'sam.taylor@northwind.example', to: conn.address, auth: 'none' });
    expect(senderAuthentication(await parseEmail(none), ['fixture.swipeback.test'])).toBe('none');
    // DKIM signed by a different domain than From is not aligned.
    const raw = buildEml({ from: 'sam.taylor@northwind.example', to: conn.address, auth: 'none', extraHeaders: {} })
      .toString()
      .replace('From:', 'Authentication-Results: fixture.swipeback.test; dkim=pass header.d=evil.example\r\nFrom:');
    expect(senderAuthentication(await parseEmail(Buffer.from(raw)), ['fixture.swipeback.test'])).toBe('none');
  });

  it('flags auto-replies, bulk mail, bounces and our own messages as auto-generated', async () => {
    const own = ['finance@northwind.example'];
    const cases = [
      { 'Auto-Submitted': 'auto-replied' },
      { Precedence: 'bulk' },
      { 'List-Id': '<news.example>' },
      { 'X-Swipeback-Outbound': '1' },
    ];
    for (const extraHeaders of cases) {
      const e = await parseEmail(buildEml({ from: 'sam.taylor@northwind.example', to: conn.address, extraHeaders }));
      expect(isAutoGenerated(e, own)).toBe(true);
    }
    expect(isAutoGenerated(await parseEmail(buildEml({ from: 'mailer-daemon@googlemail.com', to: conn.address })), own)).toBe(true);
    expect(isAutoGenerated(await parseEmail(buildEml({ from: 'sam.taylor@northwind.example', to: conn.address })), own)).toBe(false);
  });

  it('strips quoted history so only the new reply text is used', () => {
    const text = 'Lunch with the Acme site team\n\nOn Sat, 17 Oct 2026 at 10:02, Swipeback <finance@northwind.example>\nwrote:\n> What was the business purpose?\n> SYNTHETIC DEMO';
    expect(stripQuotedReply(text)).toBe('Lunch with the Acme site team');
    expect(stripQuotedReply('Company card\n-- \nSam Taylor\nField Engineer')).toBe('Company card');
  });

  it('screens attachments whose content does not match their declared type', async () => {
    const fake = buildEml({ from: 'sam.taylor@northwind.example', to: conn.address, attachments: [{ filename: 'r.pdf', mime: 'application/pdf', content: 'MZ\x90\x00 not a pdf' }] });
    const event = await adapter.normaliseInbound(await adapter.verifyInbound(conn, { body: fake, headers: {} }));
    expect(event.attachments[0]).toMatchObject({ scan: 'REJECTED' });
  });

  it('rejects unparseable input as MALFORMED', async () => {
    await expect(adapter.verifyInbound(conn, { body: Buffer.from('not an email'), headers: {} })).rejects.toBeInstanceOf(InboundRejectedError);
  });
});

describe('synthetic chat specifics', () => {
  const conn: ConnectionContext = { tenantId, connectionId: randomUUID(), channel: 'synthetic', provider: 'synthetic-chat', address: 'bot' };

  it('rejects replays outside the 5-minute window', async () => {
    const now = new Date('2026-10-17T10:00:00Z');
    const adapter = new SyntheticChatAdapter(new MemoryEvidenceStore(), new MemorySink(), SECRET, () => now);
    const body = JSON.stringify({ eventId: 'e1', from: 'chat:sam.taylor', text: 'hi', sentAt: now.toISOString() });
    const old = signSyntheticRequest(SECRET, body, now.getTime() / 1000 - 301);
    await expect(adapter.verifyInbound(conn, { body: Buffer.from(body), headers: { [SIGNATURE_HEADER]: old } })).rejects.toMatchObject({ reason: 'STALE_TIMESTAMP' });
    const fresh = signSyntheticRequest(SECRET, body, now.getTime() / 1000 - 10);
    await expect(adapter.verifyInbound(conn, { body: Buffer.from(body), headers: { [SIGNATURE_HEADER]: fresh } })).resolves.toBeTruthy();
  });

  it('rejects a signature made with the wrong secret', async () => {
    const adapter = new SyntheticChatAdapter(new MemoryEvidenceStore(), new MemorySink(), SECRET);
    const body = JSON.stringify({ eventId: 'e2', from: 'chat:sam.taylor', text: 'hi', sentAt: new Date().toISOString() });
    const sig = signSyntheticRequest('another-secret-0123456789', body, Math.floor(Date.now() / 1000));
    await expect(adapter.verifyInbound(conn, { body: Buffer.from(body), headers: { [SIGNATURE_HEADER]: sig } })).rejects.toMatchObject({ reason: 'BAD_SIGNATURE' });
  });
});
