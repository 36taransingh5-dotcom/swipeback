import { randomUUID } from 'node:crypto';
import { simpleParser, type AddressObject } from 'mailparser';
import type { SenderAuth } from '../contract.ts';

export interface ParsedAttachment {
  filename: string | null;
  contentType: string;
  content: Buffer;
}

export interface ParsedEmail {
  messageId: string | null;
  inReplyTo: string | null;
  references: string[];
  subject: string | null;
  from: { address: string; name: string | null } | null;
  recipients: string[];
  date: string | null;
  text: string;
  attachments: ParsedAttachment[];
  /** Raw header lines in order, lower-cased keys. */
  headerLines: { key: string; value: string }[];
}

export async function parseEmail(raw: Buffer): Promise<ParsedEmail> {
  const m = await simpleParser(raw, { skipImageLinks: true, skipTextToHtml: true, skipTextLinks: true });
  const addresses = (a: AddressObject | AddressObject[] | undefined) =>
    (Array.isArray(a) ? a : a ? [a] : []).flatMap((o) => o.value.map((v) => v.address?.toLowerCase()).filter((x): x is string => !!x));
  const fromValue = m.from?.value[0];
  const refs = Array.isArray(m.references) ? m.references : m.references ? m.references.split(/\s+/) : [];
  const headerLines = (m.headerLines ?? []).map((h) => ({
    key: h.key.toLowerCase(),
    value: h.line.slice(h.line.indexOf(':') + 1).replace(/\r?\n[ \t]+/g, ' ').trim(),
  }));
  const deliveredTo = headerLines.filter((h) => h.key === 'delivered-to' || h.key === 'x-original-to').map((h) => h.value.toLowerCase());
  return {
    messageId: m.messageId ?? null,
    inReplyTo: m.inReplyTo ?? null,
    references: refs.filter(Boolean),
    subject: m.subject ?? null,
    from: fromValue?.address ? { address: fromValue.address.toLowerCase(), name: fromValue.name || null } : null,
    recipients: [...new Set([...addresses(m.to), ...addresses(m.cc), ...deliveredTo])],
    date: m.date && !Number.isNaN(m.date.getTime()) ? m.date.toISOString() : null,
    text: m.text ?? (typeof m.html === 'string' ? htmlToText(m.html) : ''),
    attachments: m.attachments
      .filter((a) => a.contentDisposition !== 'inline' || !a.contentType.startsWith('image/') || a.filename)
      .map((a) => ({ filename: a.filename ?? null, contentType: a.contentType, content: a.content })),
    headerLines,
  };
}

function htmlToText(html: string): string {
  return html
    .replace(/<(script|style)[\s\S]*?<\/\1>/gi, '')
    .replace(/<br\s*\/?>/gi, '\n')
    .replace(/<\/(p|div|tr|li|h\d)>/gi, '\n')
    .replace(/<[^>]+>/g, ' ')
    .replace(/&nbsp;/g, ' ')
    .replace(/&amp;/g, '&')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&pound;/g, '£');
}

function domainOf(address: string): string {
  return address.slice(address.lastIndexOf('@') + 1).toLowerCase();
}

/**
 * Sender authentication from the topmost Authentication-Results header, trusted only when it was
 * stamped by our own receiving server (authserv-id). Lower A-R headers can be forged by senders.
 * DMARC pass, or DKIM pass with a signing domain aligned to the From domain, counts; SPF alone does not.
 */
export function senderAuthentication(email: ParsedEmail, trustedAuthservIds: readonly string[]): SenderAuth {
  if (!email.from) return 'none';
  const top = email.headerLines.find((h) => h.key === 'authentication-results');
  if (!top) return 'none';
  const [authserv, ...results] = top.value.split(';').map((s) => s.trim());
  const authservId = authserv?.split(/\s+/)[0]?.toLowerCase();
  if (!authservId || !trustedAuthservIds.includes(authservId)) return 'none';
  const fromDomain = domainOf(email.from.address);
  const aligned = (d: string | undefined) => !!d && (fromDomain === d.toLowerCase() || fromDomain.endsWith(`.${d.toLowerCase()}`));
  for (const r of results) {
    const method = /^(dkim|dmarc)=(\w+)/i.exec(r);
    if (!method || method[2]!.toLowerCase() !== 'pass') continue;
    if (method[1]!.toLowerCase() === 'dmarc' && aligned(/header\.from=([^\s;]+)/i.exec(r)?.[1])) return 'dkim_aligned';
    if (method[1]!.toLowerCase() === 'dkim' && aligned(/header\.(?:d|i)=@?([^\s;]+)/i.exec(r)?.[1])) return 'dkim_aligned';
  }
  return 'none';
}

export const OUTBOUND_MARKER_HEADER = 'x-swipeback-outbound';

/** Auto-replies, bounces, lists and our own outbound mail must never trigger a response. */
export function isAutoGenerated(email: ParsedEmail, ownAddresses: readonly string[]): boolean {
  const header = (k: string) => email.headerLines.find((h) => h.key === k)?.value.toLowerCase();
  const autoSubmitted = header('auto-submitted');
  if (autoSubmitted && autoSubmitted !== 'no') return true;
  if (/^(bulk|junk|list|auto_reply)$/.test(header('precedence') ?? '')) return true;
  if (header('list-id') || header('list-unsubscribe')) return true;
  if (header('x-autoreply') || header('x-autorespond') || header('x-auto-response-suppress')?.includes('all')) return true;
  if (header(OUTBOUND_MARKER_HEADER)) return true;
  const from = email.from?.address ?? '';
  if (/^(mailer-daemon|postmaster|no-?reply|do-?not-?reply|bounce)[@+.]/i.test(from)) return true;
  return ownAddresses.some((a) => a.toLowerCase() === from);
}

/** Remove quoted history and signatures so only the sender's new words remain. */
export function stripQuotedReply(text: string): string {
  const lines = text.replace(/\r\n?/g, '\n').split('\n');
  const out: string[] = [];
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i]!;
    // "On <date>, <name> wrote:" — Gmail sometimes wraps it over two lines.
    if (/^\s*On\s/.test(line) && (/wrote:\s*$/.test(line) || /wrote:\s*$/.test(lines[i + 1] ?? ''))) break;
    if (/^-{2,}\s*Original Message\s*-{2,}/i.test(line)) break;
    if (/^_{5,}\s*$/.test(line)) break;
    if (/^From: .+/.test(line) && out.length > 0 && out[out.length - 1]!.trim() === '') break;
    if (/^-- ?$/.test(line)) break;
    if (/^\s*>/.test(line)) continue;
    out.push(line);
  }
  return out.join('\n').trim();
}

const TOKEN_RE = /\+q-([a-z0-9]{8,32})@/i;
export function correlationTokenFrom(recipients: readonly string[]): string | null {
  for (const r of recipients) {
    const m = TOKEN_RE.exec(r);
    if (m) return m[1]!.toLowerCase();
  }
  return null;
}

export function addressMatchesConnection(recipient: string, connectionAddress: string): boolean {
  const [local, domain] = connectionAddress.toLowerCase().split('@');
  const r = recipient.toLowerCase();
  return r === `${local}@${domain}` || (r.startsWith(`${local}+`) && r.endsWith(`@${domain}`));
}

export function plusAddress(connectionAddress: string, token: string): string {
  const [local, domain] = connectionAddress.split('@');
  return `${local}+q-${token}@${domain}`;
}

// ---- Outbound MIME --------------------------------------------------------------------------

export interface OutboundMime {
  from: string;
  fromName: string;
  to: string;
  replyTo: string | null;
  subject: string;
  text: string;
  messageId: string;
  inReplyTo: string | null;
  references: readonly string[];
}

export function newMessageId(domain: string): string {
  return `<sb-${randomUUID()}@${domain}>`;
}

function encodeHeader(value: string): string {
  // RFC 2047 for non-ASCII header values; strip CR/LF to prevent header injection.
  const clean = value.replace(/[\r\n]+/g, ' ');
  return /^[\x20-\x7e]*$/.test(clean) ? clean : `=?UTF-8?B?${Buffer.from(clean, 'utf8').toString('base64')}?=`;
}

/** Plain-text RFC 5322 message with threading headers and the outbound marker (anti-loop). */
export function buildOutboundMime(m: OutboundMime): string {
  const headers = [
    `From: ${encodeHeader(m.fromName)} <${m.from}>`,
    `To: <${m.to}>`,
    ...(m.replyTo ? [`Reply-To: <${m.replyTo}>`] : []),
    `Subject: ${encodeHeader(m.subject)}`,
    `Message-ID: ${m.messageId}`,
    ...(m.inReplyTo ? [`In-Reply-To: ${m.inReplyTo}`] : []),
    ...(m.references.length ? [`References: ${m.references.join(' ')}`] : []),
    `Date: ${new Date().toUTCString()}`,
    'MIME-Version: 1.0',
    'Content-Type: text/plain; charset=utf-8',
    'Content-Transfer-Encoding: base64',
    'Auto-Submitted: auto-replied',
    `X-Swipeback-Outbound: 1`,
  ];
  const body = Buffer.from(m.text, 'utf8').toString('base64').replace(/.{76}/g, '$&\r\n');
  return `${headers.join('\r\n')}\r\n\r\n${body}\r\n`;
}
