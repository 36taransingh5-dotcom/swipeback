import { randomUUID } from 'node:crypto';
import type { ConnectionContext, InboundAttachment, InboundMessageV1, SenderAuth } from '../contract.ts';
import { inboundMessageV1Schema } from '../contract.ts';
import type { EvidenceStore } from '../evidence-store.ts';
import { dedupeKeyFor, normaliseMime, sanitiseShort, sanitiseUntrustedText, screenAttachment } from '../sanitise.ts';
import { correlationTokenFrom, isAutoGenerated, stripQuotedReply, type ParsedEmail } from './mime.ts';

const MAX_ATTACHMENTS = 10;

/** Shared by every email provider adapter (fixture, Gmail, IMAP). */
export async function normaliseEmail(args: {
  connection: ConnectionContext;
  email: ParsedEmail;
  senderAuth: SenderAuth;
  providerEventId: string;
  threadId: string | null;
  receivedAt: string;
  evidence: EvidenceStore;
}): Promise<InboundMessageV1> {
  const { connection, email, evidence } = args;
  const attachments: InboundAttachment[] = [];
  for (const a of email.attachments.slice(0, MAX_ATTACHMENTS)) {
    const mime = normaliseMime(a.contentType);
    const screen = screenAttachment(mime, a.content);
    const stored = await evidence.put(connection.tenantId, a.content);
    attachments.push({
      sha256: stored.sha256,
      mime,
      sizeBytes: stored.sizeBytes,
      storageKey: stored.storageKey,
      filename: sanitiseShort(a.filename, 255),
      scan: screen.scan,
      scanNote: screen.note,
    });
  }
  const event: InboundMessageV1 = {
    schema: 'swipeback.inbound.v1',
    tenantId: connection.tenantId,
    channel: 'email',
    connectionId: connection.connectionId,
    providerEventId: args.providerEventId,
    dedupeKey: dedupeKeyFor('email', connection.connectionId, args.providerEventId),
    receivedAt: args.receivedAt,
    providerTimestamp: email.date,
    sender: {
      channelAddress: email.from?.address ?? 'unknown@invalid',
      displayName: sanitiseShort(email.from?.name, 200),
      authentication: args.senderAuth,
    },
    conversation: {
      threadId: args.threadId,
      messageId: email.messageId,
      inReplyTo: email.inReplyTo,
      references: email.references.slice(-100),
      correlationToken: correlationTokenFrom(email.recipients),
    },
    subject: sanitiseShort(email.subject, 998),
    text: sanitiseUntrustedText(stripQuotedReply(email.text)),
    attachments,
    action: null, // email never carries a signed action; approvals happen on the authenticated review page
    consent: { source: 'connected_mailbox', scope: `mailbox:${connection.address}` },
    autoGenerated: isAutoGenerated(email, [connection.address]),
    correlationId: randomUUID(),
  };
  return inboundMessageV1Schema.parse(event);
}

/** Thread root for providers without native thread ids: first References id, else In-Reply-To, else own id. */
export function rfcThreadRoot(email: ParsedEmail): string | null {
  return email.references[0] ?? email.inReplyTo ?? email.messageId;
}
