import { z } from 'zod';

/**
 * The channel adapter contract (PRD §17.2, §17.5). Every channel — email, the synthetic chat
 * channel, Slack, and future WhatsApp / Telegram / Apple Messages adapters — is a transport that
 * turns provider payloads into a versioned InboundMessage and delivers rendered messages.
 *
 * Adapters never touch expenses, approvals or payouts. They receive only ports (evidence store,
 * outbound sink/provider client) and the connection they act for.
 */

export const CHANNELS = ['email', 'slack', 'whatsapp', 'telegram', 'imessage', 'synthetic'] as const;
export type Channel = (typeof CHANNELS)[number];

/** How strongly the provider vouches for the sender address. Identity mapping requires a minimum per channel. */
export type SenderAuth = 'dkim_aligned' | 'platform_signed' | 'none';

const sha256 = z.string().regex(/^[0-9a-f]{64}$/);

export const inboundAttachmentSchema = z.object({
  sha256,
  mime: z.string().min(1).max(127),
  sizeBytes: z.number().int().nonnegative(),
  storageKey: z.string().min(1),
  /** Untrusted: shown to reviewers, never used for decisions. */
  filename: z.string().max(255).nullable(),
  scan: z.enum(['UNSCANNED', 'CLEAN', 'REJECTED']),
  scanNote: z.string().max(200).nullable(),
});
export type InboundAttachment = z.infer<typeof inboundAttachmentSchema>;

export const inboundMessageV1Schema = z.object({
  schema: z.literal('swipeback.inbound.v1'),
  tenantId: z.uuid(),
  channel: z.enum(CHANNELS),
  connectionId: z.uuid(),
  providerEventId: z.string().min(1).max(998),
  /** sha256(channel | connectionId | providerEventId): the idempotency key for this event. */
  dedupeKey: sha256,
  receivedAt: z.iso.datetime({ offset: true }),
  providerTimestamp: z.iso.datetime({ offset: true }).nullable(),
  sender: z.object({
    /** Normalised provider address (email address, chat handle). Identity is looked up from this. */
    channelAddress: z.string().min(1).max(320),
    /** Untrusted, display only — never used to infer identity. */
    displayName: z.string().max(200).nullable(),
    authentication: z.enum(['dkim_aligned', 'platform_signed', 'none']),
  }),
  conversation: z.object({
    threadId: z.string().max(998).nullable(),
    messageId: z.string().max(998).nullable(),
    inReplyTo: z.string().max(998).nullable(),
    references: z.array(z.string().max(998)).max(100),
    /** Token from a Swipeback-issued reply address (e.g. finance+q-<token>@...). */
    correlationToken: z.string().max(64).nullable(),
  }),
  subject: z.string().max(998).nullable(),
  /** Untrusted data. Sanitised; quoted reply history removed where the channel has it. */
  text: z.object({ sanitised: z.string().max(20_000), truncated: z.boolean() }),
  attachments: z.array(inboundAttachmentSchema).max(10),
  /** Signed interactive action (button press). Only adapters that can verify signatures set it. */
  action: z
    .object({ challengeId: z.string().min(1), nonce: z.string().min(1), verb: z.enum(['APPROVE', 'DECLINE', 'REQUEST_INFO']) })
    .nullable(),
  consent: z.object({ source: z.enum(['connected_mailbox', 'bot_dm', 'simulator']), scope: z.string().min(1) }),
  /** Auto-replies, bulk mail, bounces and our own messages: recorded but never answered (anti-loop). */
  autoGenerated: z.boolean(),
  correlationId: z.uuid(),
});
export type InboundMessageV1 = z.infer<typeof inboundMessageV1Schema>;

export interface ConnectionContext {
  tenantId: string;
  connectionId: string;
  channel: Channel;
  provider: string;
  /** The designated address / bot identity this connection receives on. */
  address: string;
}

export interface RawInbound {
  body: Buffer;
  headers: Readonly<Record<string, string>>;
  /** Provider-assigned ids known before parsing (e.g. Gmail message/thread id). */
  providerMessageId?: string;
  providerThreadId?: string;
}

export interface VerifiedInbound<P = unknown> {
  connection: ConnectionContext;
  providerEventId: string;
  senderAuth: SenderAuth;
  payload: P;
  receivedAt: string;
}

export interface OutboundEnvelope {
  tenantId: string;
  connectionId: string;
  /** Sending identity: the connection's own address / bot id. */
  from: string;
  /** Recipient channel address. */
  to: string;
  subject: string | null;
  text: string;
  threadId: string | null;
  inReplyTo: string | null;
  references: readonly string[];
  /** Token to embed in the reply address so answers correlate even if threading breaks. */
  replyToken: string | null;
  idempotencyKey: string;
}

export interface ApprovalRequest extends OutboundEnvelope {
  /** Authenticated review page; never a link that approves by itself. */
  reviewUrl: string;
  actions: readonly ('APPROVE' | 'DECLINE' | 'REQUEST_INFO')[];
}

export interface SendResult {
  providerMessageId: string;
  threadId: string | null;
  /** RFC 5322 Message-ID we stamped on the message (email), so later messages can reply to it. */
  rfcMessageId?: string;
}

export type DeliveryState = 'ACCEPTED' | 'DELIVERED' | 'READ' | 'FAILED' | 'UNKNOWN';

export interface ChannelCapabilities {
  attachments: boolean;
  threading: boolean;
  interactiveActions: boolean;
  deliveryReceipts: boolean;
  businessInitiatedMessages: 'free' | 'template_only' | 'none';
}

export interface ChannelAdapter<P = unknown> {
  readonly channel: Channel;
  readonly provider: string;
  readonly capabilities: ChannelCapabilities;
  /** Authenticate the request (signature / OAuth source / DKIM). Throws InboundRejectedError. */
  verifyInbound(connection: ConnectionContext, raw: RawInbound): Promise<VerifiedInbound<P>>;
  /** Produce the versioned event; attachments are stored as immutable evidence first. */
  normaliseInbound(verified: VerifiedInbound<P>): Promise<InboundMessageV1>;
  sendMessage(message: OutboundEnvelope): Promise<SendResult>;
  sendApprovalRequest(request: ApprovalRequest): Promise<SendResult>;
  getDeliveryState?(providerMessageId: string): Promise<DeliveryState>;
}

export type InboundRejection =
  | 'BAD_SIGNATURE'
  | 'STALE_TIMESTAMP'
  | 'MALFORMED'
  | 'NOT_ADDRESSED_TO_CONNECTION'
  | 'TOO_LARGE';

export class InboundRejectedError extends Error {
  override readonly name = 'InboundRejectedError';
  constructor(
    readonly reason: InboundRejection,
    message?: string,
  ) {
    super(message ?? reason);
  }
}
